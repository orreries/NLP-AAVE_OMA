def load_script(file_path):
    with open(file_path, 'r', encoding='utf-8') as f:
        return f.read()

#  uses word boundaries so 'int.' / 'ext.' aren't stripped out of the middle of words
# (e.g. "point." or "text."), and the text is lowercased first so the (v.o.) patterns can match
def cleaning(data):
    data = data.lower()
    to_remove = [
        r'\(v\.o\.\)',
        r"\(cont'?d\)",
        r'\(contd\)',
        r'\bext\.',
        r'\bint\.',
        r'\.\.\.',
        r"'",
    ]
    for pattern in to_remove:
        data = re.sub(pattern, '', data)
    return ' '.join(data.split())  # removes \n, \r and collapses multiple spaces

