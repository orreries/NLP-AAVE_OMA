import re
from collections import Counter

def analyze_aave_lexicon(text, aave_terms, top_n=15):
    """
    Analyze AAVE usage in a block of text.

    Parameters:
        text (str): the script or tweet corpus
        aave_terms (list): list of cleaned AAVE terms (unigrams only recommended)
        top_n (int): number of top AAVE terms to return

    Returns:
        dict with:
            - total_words
            - total_aave_terms
            - aave_density
            - aave_coverage
            - unique_aave_terms_found
            - top_aave_terms (list of tuples)
    """

    # basic normalization
    text = text.lower()
    tokens = text.split()

    total_words = len(tokens)

    # convert to set for fast membership testing
    aave_set = set(aave_terms)

    # all aave tokens in script
    aave_tokens = [t for t in tokens if t in aave_set]

    # counts
    total_aave_terms = len(aave_tokens)
    unique_aave_terms_found = sorted(set(aave_tokens))

    # density = proportion of AAVE tokens in the script
    aave_density = total_aave_terms / total_words if total_words > 0 else 0

    # coverage = % of dictionary present in the script
    aave_coverage = len(unique_aave_terms_found) / len(aave_set) if len(aave_set) > 0 else 0

    # top N frequent AAVE tokens
    freq = Counter(aave_tokens)
    top_aave_terms = freq.most_common(top_n)

    return {
        "total_words": total_words,
        "total_aave_terms": total_aave_terms,
        "aave_density": aave_density,
        "aave_coverage": aave_coverage,
        "unique_aave_terms_found": unique_aave_terms_found,
        "top_aave_terms": top_aave_terms
    }

